// Generates src/data/flags.ts: one SVG string per country, so flags render
// identically everywhere (emoji flags show as two letters on Windows).
//
// Source: country-flag-icons by @catamphetamine (MIT), 3:2 versions.
// Re-run with: npm run flags
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkgDir = require.resolve("country-flag-icons/package.json").replace(/package\.json$/, "");
const countriesSource = readFileSync(new URL("../src/data/countries.ts", import.meta.url), "utf8");
const codes = [...countriesSource.matchAll(/"cca2": "([A-Z]{2})"/g)].map((m) => m[1]).sort();

const flags = {};
for (const code of codes) {
  flags[code] = readFileSync(`${pkgDir}3x2/${code}.svg`, "utf8").replace(/\s*\n\s*/g, " ").trim();
}

const out =
  `// AUTO-GENERATED by scripts/prepare-flags.mjs — do not hand-edit.\n` +
  `// Flags: country-flag-icons by @catamphetamine (MIT License), 3:2 aspect ratio.\n` +
  `export const FLAG_SVGS: Record<string, string> = ${JSON.stringify(flags, null, 0).replace(/","/g, '",\n  "').replace(/^\{"/, '{\n  "').replace(/"\}$/, '"\n}')};\n`;
writeFileSync(new URL("../src/data/flags.ts", import.meta.url), out);
const bytes = Object.values(flags).reduce((s, v) => s + v.length, 0);
console.log(`Flags: ${codes.length} countries, ${(bytes / 1024).toFixed(0)} KB of SVG`);
